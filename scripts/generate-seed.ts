import { writeFileSync } from "node:fs";
import { DOCUMENTS } from "../lib/documents";

function sqlString(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

const rows = DOCUMENTS.map((document) => {
  const topics = `array[${document.topics.map(sqlString).join(", ")}]::text[]`;
  const embedding = `'[${document.embedding.join(",")}]'::vector`;
  return `  (${sqlString(document.id)}, ${sqlString(document.title)}, ${sqlString(document.body)}, ${sqlString(document.language)}, ${topics}, ${embedding})`;
});

const sql = `-- Generated by \`npm run generate:seed\` from lib/documents.ts.
-- Re-run the script after editing the corpus. Do not edit by hand.

insert into public.documents (id, title, body, language, topics, embedding)
values
${rows.join(",\n")};
`;

const target = "supabase/migrations/20261010170100_seed_documents.sql";
writeFileSync(target, sql);
console.log(`Wrote ${DOCUMENTS.length} documents to ${target}`);
